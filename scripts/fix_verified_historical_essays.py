def main():
    text = PATH.read_text(encoding='utf-8')
    a = text.find(START)
    b = text.find(END, a)
    if a < 0 or b < 0:
        raise SystemExit('ESSAYS block not found')
    json_start = a + len(START)
    essays = json.loads(text[json_start:b])
    by_id = {e.get('id'): e for e in essays}

    missing = sorted(set(CORRECTIONS) - set(by_id))
    if missing:
        raise SystemExit('missing essay IDs: ' + ', '.join(missing))

    changed = 0
    for eid, patch in CORRECTIONS.items():
        row = by_id[eid]
        for key, value in patch.items():
            if row.get(key) != value:
                row[key] = value
                changed += 1

    encoded = json.dumps(essays, ensure_ascii=False, separators=(',', ':'))
    out = text[:json_start] + encoded + text[b:]
    PATH.write_text(out, encoding='utf-8')

    final = PATH.read_text(encoding='utf-8')
    bad_tokens = [
        '【分析】',
        'ErikErikson',
        'malpracticc',
        '兒少保護牆至親職教育',
        '該個按的問題性質',
        '請問鑑對於委託',
        '準備結東',
        '與男友有性關 的男友同居',
    ]
    still_bad = [x for x in bad_tokens if x in final]
    if still_bad:
        raise SystemExit('known corrupted text remains: ' + ', '.join(still_bad))

    # Specific completeness guards for formerly truncated questions.
    guards = [
        '請依 Reamer 所提出的分配有限資源的四種標準',
        '同時運用此三種理論觀點',
        '四個主要工作階段（開始階段、評估階段、處遇階段與結案階段）',
        '說明在準備階段需進行那些工作',
    ]
    missing_guards = [x for x in guards if x not in final]
    if missing_guards:
        raise SystemExit('completeness guard failed: ' + ', '.join(missing_guards))

    print(f'Verified historical essay corrections applied: {len(CORRECTIONS)} essays, {changed} fields changed.')


if __name__ == '__main__':
    main()
